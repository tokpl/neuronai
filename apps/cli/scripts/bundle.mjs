import { createHash } from 'node:crypto';
import { chmod, cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

import { build } from 'esbuild';

/**
 * `neuronai` ships as one self-contained package.
 *
 * Publishing the workspace libraries separately meant a user's install pulled a
 * dozen `@neuronai/*` packages that all had to exist at exactly the same version.
 * Bundling removes that coupling entirely: one tarball, one version, nothing to skew.
 *
 * Only the MCP SDK stays external — it is a real third-party dependency with its
 * own transitive tree, declared in package.json.
 */
const cliRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(cliRoot, '..', '..');
const dist = join(cliRoot, 'dist');

// Always rebuild workspace packages when this script is invoked directly.
spawnSync(process.execPath, [join(cliRoot, 'scripts', 'ensure-workspace-built.mjs')], {
  cwd: cliRoot,
  stdio: 'inherit',
});

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

const brainPkg = JSON.parse(
  await readFile(join(repoRoot, 'packages', 'brain', 'package.json'), 'utf8'),
);
const cliPkg = JSON.parse(await readFile(join(cliRoot, 'package.json'), 'utf8'));
const rankSrc = await readFile(
  join(repoRoot, 'packages', 'brain', 'src', 'retrieval', 'rank.ts'),
  'utf8',
);
const fingerprint = createHash('sha1')
  .update(`${brainPkg.version}\n${rankSrc}`)
  .digest('hex')
  .slice(0, 12);

// Keep runtime -v in lockstep with package.json (no more stale hardcoded CLI_VERSION).
await writeFile(
  join(cliRoot, 'src', 'cli-version.generated.ts'),
  `/** Auto-generated by scripts/bundle.mjs — do not edit. */\n` +
    `export const CLI_VERSION = ${JSON.stringify(cliPkg.version)};\n`,
  'utf8',
);

// Generated before esbuild so the hash is part of the bundle without breaking the shebang.
await writeFile(
  join(cliRoot, 'src', 'brain-fingerprint.generated.ts'),
  `/** Auto-generated by scripts/bundle.mjs — do not edit. */\n` +
    `export const NEURON_BRAIN_FINGERPRINT = ${JSON.stringify({
      brainVersion: brainPkg.version,
      rankSha: fingerprint,
    })} as const;\n`,
  'utf8',
);

const result = await build({
  entryPoints: [join(cliRoot, 'src', 'index.ts')],
  outfile: join(dist, 'index.js'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  // src/index.ts already carries the shebang; esbuild preserves it.
  external: ['@modelcontextprotocol/sdk', '@modelcontextprotocol/sdk/*'],
  legalComments: 'none',
  minify: false,
  sourcemap: false,
  metafile: true,
});

await writeFile(
  join(dist, 'brain-fingerprint.json'),
  `${JSON.stringify({ brainVersion: brainPkg.version, rankSha: fingerprint }, null, 2)}\n`,
  'utf8',
);

await cp(join(repoRoot, 'packages', 'cursor-integration', 'templates'), join(dist, 'templates'), {
  recursive: true,
});

await chmod(join(dist, 'index.js'), 0o755);

const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
console.log(
  `bundled dist/index.js (${Math.round(bytes / 1024)} KB), neuronai ${cliPkg.version}, brain ${brainPkg.version}@${fingerprint}, templates copied`,
);
