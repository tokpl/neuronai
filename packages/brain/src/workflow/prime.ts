import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { nowIso } from '../defaults.js';
import type { BrainPrefs, WorkflowPrefs } from '../models.js';
import type { ProjectBrain } from '../project-brain.js';

export interface DetectedConventions {
  packageManager?: string;
  scripts: NonNullable<WorkflowPrefs['scripts']>;
  defaultBranch?: string;
}

export interface PrimeResult {
  conventions: DetectedConventions;
  prefsPath: string;
  projectMapPath: string;
  primedAt: string;
}

async function readJsonSafe<T>(path: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(path, 'utf8')) as T;
  } catch {
    return null;
  }
}

/** Detect package manager + scripts from the repo (no LLM). */
export async function detectConventions(projectRoot: string): Promise<DetectedConventions> {
  const scripts: NonNullable<WorkflowPrefs['scripts']> = {};
  let packageManager: string | undefined;

  if (existsSync(join(projectRoot, 'pnpm-lock.yaml'))) packageManager = 'pnpm';
  else if (existsSync(join(projectRoot, 'yarn.lock'))) packageManager = 'yarn';
  else if (existsSync(join(projectRoot, 'bun.lockb')) || existsSync(join(projectRoot, 'bun.lock')))
    packageManager = 'bun';
  else if (existsSync(join(projectRoot, 'package-lock.json'))) packageManager = 'npm';

  const pkg = await readJsonSafe<{ scripts?: Record<string, string> }>(
    join(projectRoot, 'package.json'),
  );
  const run = (name: string) => {
    if (!pkg?.scripts?.[name]) return undefined;
    if (packageManager === 'pnpm') return `pnpm ${name === 'test' ? 'test' : `run ${name}`}`;
    if (packageManager === 'yarn') return `yarn ${name}`;
    if (packageManager === 'bun') return `bun run ${name}`;
    return `npm run ${name}`;
  };

  // test is often `npm test` without run
  if (pkg?.scripts?.['test']) {
    scripts.test =
      packageManager === 'pnpm'
        ? 'pnpm test'
        : packageManager === 'yarn'
          ? 'yarn test'
          : packageManager === 'bun'
            ? 'bun test'
            : 'npm test';
  }
  scripts.lint = run('lint');
  scripts.typecheck = run('typecheck') ?? run('type-check');
  scripts.format = run('format') ?? run('fmt');
  scripts.build = run('build');

  let defaultBranch = 'main';
  try {
    const { execSync } = await import('node:child_process');
    const ref = execSync('git symbolic-ref --short refs/remotes/origin/HEAD', {
      cwd: projectRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    const m = ref.match(/origin\/(.+)$/);
    if (m?.[1]) defaultBranch = m[1];
  } catch {
    // keep main
  }

  return { packageManager, scripts, defaultBranch };
}

function renderProjectMap(brain: ProjectBrain, conventions: DetectedConventions): string {
  const name =
    brain.dna.identity.name?.value ?? brain.prefs?.project?.name ?? 'project';
  const stack =
    brain.dna.stack.tags?.value?.join(', ') ??
    brain.prefs?.project?.stack?.join(', ') ??
    'unknown';
  const modules = brain.dna.structure.modules?.value ?? [];
  const mapEntries = brain.knowledge.map?.entries?.slice(0, 40) ?? [];
  const decisions = brain.knowledge.decisions.slice(0, 12);

  const lines = [
    `# Project map — ${name}`,
    '',
    `Generated by \`neuron prime\` at ${nowIso()}.`,
    '',
    '## Stack',
    '',
    `- Tags: ${stack}`,
    `- Package manager: ${conventions.packageManager ?? 'n/a'}`,
    `- Default branch: ${conventions.defaultBranch ?? 'main'}`,
    '',
    '## Scripts (use these for verify)',
    '',
    ...Object.entries(conventions.scripts)
      .filter(([, v]) => Boolean(v))
      .map(([k, v]) => `- **${k}**: \`${v}\``),
    '',
    '## Modules',
    '',
    ...(modules.length ? modules.map((m) => `- ${m}`) : ['- (run `neuron scan --deep` to enrich)']),
    '',
    '## Map entries (sample)',
    '',
    ...(mapEntries.length
      ? mapEntries.map((e) => `- \`${e.path}\` — ${e.name}${e.purpose ? ` (${e.purpose})` : ''}`)
      : ['- (empty — scan the project)']),
    '',
    '## Decisions (sample)',
    '',
    ...(decisions.length
      ? decisions.map((d) => `- **${d.title}**: ${d.content.slice(0, 160)}`)
      : ['- (none yet — deliver and remember will grow this)']),
    '',
    '## Next',
    '',
    '- `/neuron-deliver` for gated builds',
    '- `neuron_context` before exploring',
    '',
  ];
  return lines.join('\n');
}

/**
 * Deterministic prime: detect conventions, merge workflow prefs, write living map.
 * Does not interview — called from `neuron init` (and optional `neuron prime` refresh).
 */
export async function runPrime(
  brain: ProjectBrain,
  options: { defaults?: Partial<WorkflowPrefs> } = {},
): Promise<PrimeResult> {
  const conventions = await detectConventions(brain.paths.projectRoot);
  const primedAt = nowIso();

  const workflow: WorkflowPrefs = {
    outputStyle: 'normal',
    autonomy: 'gate-all',
    tdd: 'strict',
    specDir: 'docs/plans',
    families: ['build', 'ui', 'docs', 'polish', 'maintain'],
    ...options.defaults,
    packageManager: conventions.packageManager,
    defaultBranch: conventions.defaultBranch,
    scripts: { ...conventions.scripts, ...options.defaults?.scripts },
    primedAt,
  };

  const basePrefs: BrainPrefs = brain.prefs ?? {
    schemaVersion: 1,
    project: {
      id: brain.dna.identity.projectId?.value ?? 'local',
      name: brain.dna.identity.name?.value ?? 'project',
      stack: brain.dna.stack.tags?.value ?? [],
    },
    privacy: { mode: 'suggest', localOnly: true, telemetry: false },
    memory: { autoSave: true, threshold: 0.7 },
  };

  brain.prefs = {
    ...basePrefs,
    workflow: { ...basePrefs.workflow, ...workflow },
  };

  await mkdir(brain.paths.neuronDir, { recursive: true });
  await writeFile(brain.paths.prefs, `${JSON.stringify(brain.prefs, null, 2)}\n`, 'utf8');

  const mapMd = renderProjectMap(brain, conventions);
  await writeFile(brain.paths.projectMap, mapMd, 'utf8');

  // Keep machine map plane in sync with a lightweight summary entry when empty.
  if (!brain.knowledge.map?.entries?.length) {
    const modules = brain.dna.structure.modules?.value ?? [];
    brain.knowledge = {
      ...brain.knowledge,
      map: {
        version: 1,
        updatedAt: primedAt,
        entries: modules.map((m) => ({
          kind: 'module' as const,
          name: m,
          path: m.endsWith('/') ? m : `${m}/`,
          purpose: 'from DNA modules (neuron prime)',
        })),
      },
      updatedAt: primedAt,
    };
  }

  await brain.save();

  return {
    conventions,
    prefsPath: brain.paths.prefs,
    projectMapPath: brain.paths.projectMap,
    primedAt,
  };
}

/** True when workflow.primedAt exists and PROJECT_MAP.md is on disk. */
export function isPrimed(brain: ProjectBrain): boolean {
  return Boolean(brain.prefs?.workflow?.primedAt && existsSync(brain.paths.projectMap));
}
